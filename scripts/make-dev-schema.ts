/**
 * Generate a SQLite twin of the production MySQL schema, for local development only.
 *
 * Production runs MySQL (`DATABASE_URL=mysql://…`). Running MySQL locally is a hassle, so
 * this script derives `prisma/schema.sqlite.prisma` from the real schema — same models,
 * same relations, only the MySQL-specific native types (`@db.VarChar`, `@db.Text`,
 * `@db.LongText`) are stripped, since SQLite has no equivalents.
 *
 * It is generated, never hand-edited, so it can't drift:
 *
 *   bun run db:dev:schema          # write prisma/schema.sqlite.prisma
 *   DATABASE_URL="file:./dev.db" bunx prisma db push --schema prisma/schema.sqlite.prisma
 *   DATABASE_URL="file:./dev.db" bun run db:dev:seed
 *
 * (See docs/MEDIA_HUB.md — this is NOT how you deploy.)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const source = join(root, 'prisma', 'schema.prisma')
const target = join(root, 'prisma', 'schema.sqlite.prisma')

const banner = `// AUTO-GENERATED by scripts/make-dev-schema.ts — do not edit.
// Local development twin of prisma/schema.prisma (MySQL). Regenerate instead of patching.
`

const sqlite = readFileSync(source, 'utf8')
  // datasource → sqlite
  .replace(/provider\s*=\s*"mysql"/, 'provider = "sqlite"')
  // strip MySQL native type attributes: @db.VarChar(500), @db.Text, @db.LongText, …
  .replace(/\s*@db\.[A-Za-z]+(\([^)]*\))?/g, '')
  // prisma's sqlite connector rejects the mysql-only datasource extras, if any appear later
  .replace(/\s*relationMode\s*=\s*"[^"]*"/g, '')

writeFileSync(target, banner + sqlite, 'utf8')
console.log(`✔ wrote ${target} (from ${source})`)
